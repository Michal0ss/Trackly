function bindShortWords<T extends Record<string, string>>(copy: T): T {
  return Object.fromEntries(
    Object.entries(copy).map(([key, text]) => [key, text.replace(/(?<=^|\s)([aiouwz]) /gi, '$1\u00a0')]),
  ) as T;
}

